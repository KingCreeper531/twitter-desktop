// Builds ios/Web/inject.js from the Windows page script (src/preload.js), so the
// iPhone app gets the same ad blocking and cleanup. The Electron parts the script
// uses (ipcRenderer, contextBridge, webFrame) are replaced by small stand-ins that
// talk to the iPhone app through window.webkit.messageHandlers.rw.
//   node scripts/make-ios-script.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const site = require(path.join(root, 'src', 'site.js'));
const preload = fs.readFileSync(path.join(root, 'src', 'preload.js'), 'utf8');
const defaults = Object.fromEntries(site.settings.filter((s) => s.key).map((s) => [s.key, s.default]));

const out = `// Generated by scripts/make-ios-script.js from src/preload.js. Don't edit by hand.
(function () {
  if (window.__ranchWeb) return;
  window.__ranchWeb = true;
  var handlers = {};
  var post = function (type, arg) {
    try { window.webkit.messageHandlers.rw.postMessage({ type: type, arg: arg == null ? '' : String(arg) }); } catch (e) { /* not in the app */ }
  };
  var electron = {
    ipcRenderer: {
      sendSync: function () { return ${JSON.stringify(defaults)}; },
      send: function (channel, arg) { post(channel, arg); },
      invoke: function (channel) { return Promise.resolve(channel === 'tb:update-get' ? (window.__rwUpdateState || null) : null); },
      on: function (channel, fn) { (handlers[channel] = handlers[channel] || []).push(fn); },
    },
    contextBridge: { executeInMainWorld: function (o) { return o.func.apply(null, o.args || []); } },
    webFrame: {
      insertCSS: function (css) {
        var s = document.createElement('style');
        s.textContent = css;
        (document.head || document.documentElement).appendChild(s);
        return s;
      },
      removeInsertedCSS: function (s) { if (s && s.remove) s.remove(); },
    },
  };
  var require = function () { return electron; };
  window.__rwEmit = function (channel, payload) { (handlers[channel] || []).forEach(function (fn) { fn(null, payload); }); };
  // There's no settings window on iPhone (the defaults are used), so no gear button
  electron.webFrame.insertCSS('#ranch-settings-btn { display: none !important; }' +
    ' #ranch-update-btn { position: fixed !important; top: calc(env(safe-area-inset-top) + 8px); left: 50%; transform: translateX(-50%); z-index: 99999; height: 36px !important; }');

${preload.split('\n').map((l) => `  ${l}`.trimEnd()).join('\n')}
})();
`;
fs.mkdirSync(path.join(root, 'ios', 'Web'), { recursive: true });
fs.writeFileSync(path.join(root, 'ios', 'Web', 'inject.js'), out);
console.log(`Wrote ios/Web/inject.js (${out.length} bytes)`);
